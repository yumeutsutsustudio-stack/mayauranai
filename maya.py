def is_leap(y):
    return (y % 4 == 0 and y % 100 != 0) or y % 400 == 0


def n_leap(y):
    """西暦1年〜y年までのうるう年の数"""
    return y // 4 - y // 100 + y // 400


def serial(y, m, d):
    """うるう日（2月29日）を数えない通し日数。
    2月29日は2月28日として扱う（Web版と同じ）。"""
    if m == 2 and d == 29:
        d = 28
    days = datetime.date(y, m, d).toordinal()
    cnt = n_leap(y - 1) + (1 if is_leap(y) and m > 2 else 0)
    return days - cnt


REF = serial(2013, 7, 26)  # 2013年7月26日 = KIN164


def kin_of(y, m, d):
    return (serial(y, m, d) - REF + 163) % 260 + 1


def seal_of(k):
    return (k - 1) % 20 + 1


def tone_of(k):
    return (k - 1) % 13 + 1


def wrap20(s):
    return (s - 1) % 20 + 1


def kin_from(s, t):
    for k in range(1, 261):
        if seal_of(k) == s and tone_of(k) == t:
            return k
    return None


def ws_of(k):
    """ウェイブスペルの紋章番号"""
    return seal_of(k - (tone_of(k) - 1))


def fam_of(s):
    return s % 5


def relations(k):
    s, t = seal_of(k), tone_of(k)
    off = [8, 0, 12, 4, 16][t % 5]
    guide = kin_from(wrap20(s + off), t)
    a = 19 - s
    if a <= 0:
        a += 20
    return {"guide": guide, "analog": kin_from(a, t), "anti": kin_from(wrap20(s + 10), t), "occult": 261 - k}


def age_now(y, m, d, today=None):
    """今日時点の満年齢（2月29日生まれはうるう年以外は2月28日を誕生日とする。Web版と同じ）"""
    today = today or datetime.date.today()
    last = (datetime.date(today.year + (m == 12), m % 12 + 1, 1) - datetime.timedelta(days=1)).day
    bd = datetime.date(today.year, m, min(d, last))
    return max(0, today.year - y - (1 if today < bd else 0))


