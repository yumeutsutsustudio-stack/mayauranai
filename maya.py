def ask_date(prompt):
    """「1990/05/20」形式で生年月日を入力してもらう。正しく入力されるまで繰り返す。"""
    today = datetime.date.today()
    while True:
        try:
            s = input(prompt).strip()
        except EOFError:
            print()
            sys.exit(0)
        s = s.translate(str.maketrans("０１２３４５６７８９／", "0123456789/"))
        parts = s.split("/")
        if len(parts) != 3 or not all(p.isdigit() for p in parts) or len(parts[0]) != 4:
            print(paint("  入力の形がちがいます。「1990/05/20」のように 年/月/日 で入力してください。", "r"))
            continue
        y, m, d = (int(p) for p in parts)
        try:
            dt = datetime.date(y, m, d)
        except ValueError:
            print(paint("  存在しない日付です。もう一度入力してください。", "r"))
            continue
        if y < 1900 or dt > today:
            print(paint(f"  1900/01/01 から今日（{today:%Y/%m/%d}）までの日付を入力してください。", "r"))
            continue
        return y, m, d


